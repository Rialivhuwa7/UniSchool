);

-- ============================== payments ==============================
create table collections (
    id          bigint generated by default as identity primary key,
    title       varchar(255)   not null,
    amount      numeric(12, 2) not null,
    kind        varchar(255)   not null,
    campus      varchar(255)   not null,
    due_date    date,
    instalments integer        not null,
    created_at  timestamp(6)
);
create table collection_grades (
    collection_id bigint not null references collections (id),
    grade         varchar(255)
);

create table collection_payments (
    id               bigint generated by default as identity primary key,
    collection_id    bigint         not null references collections (id),
    learner_id       bigint         not null references learners (id),
    payer_account_id bigint         not null references accounts (id),
    amount           numeric(12, 2) not null,
    tickets          integer        not null,
    method           varchar(255),
    paid_at          timestamp(6)
);
create index ix_collection_payments_collection_learner on collection_payments (collection_id, learner_id);

create table tickets (
    id            bigint generated by default as identity primary key,
    code          varchar(255) unique,
    collection_id bigint  not null references collections (id),
    account_id    bigint  not null references accounts (id),
    issued_at     timestamp(6),
    scanned       boolean not null
);

create table fee_accounts (
    id                 bigint generated by default as identity primary key,
    learner_id         bigint         not null references learners (id),
    fee_year           integer        not null,
    annual_fee         numeric(12, 2) not null,
    plan               varchar(255),
    previous_year_paid boolean        not null,
    plan_chosen_at     timestamp(6),
    constraint uk_fee_accounts_learner_year unique (learner_id, fee_year)
);

-- ============================== notices ==============================
create table notices (
    id                bigint generated by default as identity primary key,
    author_account_id bigint references accounts (id),
    from_label        varchar(255)  not null,
    campus            varchar(255)  not null,
    tag               varchar(255),
    title             varchar(255)  not null,
    body              varchar(4000) not null,
    attachment_name   varchar(255),
    requires_ack      boolean       not null,
    rsvp_enabled      boolean       not null,
    collection_id     bigint references collections (id),
    status            varchar(255)  not null,
    review_comment    varchar(1000),
    created_at        timestamp(6),
    published_at      timestamp(6)
);
create table notice_grades (
    notice_id bigint not null references notices (id),
    grade     varchar(255)
);
create table notice_teams (
    notice_id bigint not null references notices (id),
    team      varchar(255)
);

create table notice_receipts (
    id          bigint generated by default as identity primary key,
    notice_id   bigint       not null references notices (id),
    account_id  bigint       not null references accounts (id),
    learner_id  bigint references learners (id),
    type        varchar(255) not null,
    attending   boolean,
    occurred_at timestamp(6)
);
create index ix_notice_receipts_notice on notice_receipts (notice_id);

-- ============================== homework ==============================
create table homework (
    id                bigint generated by default as identity primary key,
    campus            varchar(255)  not null,
    grade             varchar(255)  not null,
    subject           varchar(255)  not null,
    title             varchar(255)  not null,
    body              varchar(2000),
    due_date          date,
    attachment_name   varchar(255),
    author_account_id bigint references accounts (id),
    by_label          varchar(255),
    status            varchar(255)  not null,
    review_comment    varchar(1000),
    created_at        timestamp(6)
);

create table homework_completions (
    id          bigint generated by default as identity primary key,
    homework_id bigint not null references homework (id),
    learner_id  bigint not null references learners (id),
    done_at     timestamp(6),
    constraint uk_homework_completions unique (homework_id, learner_id)
);

-- ============================== parent groups ==============================
create table parent_groups (
    id                   bigint generated by default as identity primary key,
    name                 varchar(255) not null,
    campus               varchar(255) not null,
    grade                varchar(255),
    team                 varchar(255),
    moderator_label      varchar(255),
    moderator_account_id bigint references accounts (id),
    mode                 varchar(255) not null
);

create table group_messages (
    id                bigint generated by default as identity primary key,
    group_id          bigint        not null references parent_groups (id),
    author_account_id bigint references accounts (id),
    author_name       varchar(255)  not null,
    author_role       varchar(255),
    body              varchar(2000) not null,
    sent_at           timestamp(6),
    deliver_at        timestamp(6),
    reports           integer       not null,
    hidden            boolean       not null
);
create index ix_group_messages_group_deliver on group_messages (group_id, deliver_at);

create table group_memberships (
    id           bigint generated by default as identity primary key,
    group_id     bigint  not null references parent_groups (id),
    account_id   bigint  not null references accounts (id),
    muted        boolean not null,
    last_read_at timestamp(6),
    constraint uk_group_memberships unique (group_id, account_id)
);
