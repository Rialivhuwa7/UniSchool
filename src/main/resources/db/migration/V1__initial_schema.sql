-- UniSchool initial schema.
-- Written for PostgreSQL; also runs on H2 in PostgreSQL mode (used by MigrationOnH2Test).
-- Never edit a migration that has run on staging or production: add V2__..., V3__... instead.

-- ============================== accounts ==============================
create table accounts (
    id             bigint generated by default as identity primary key,
    username       varchar(255)   not null unique,
    password_hash  varchar(255)   not null,
    full_name      varchar(255)   not null,
    display_name   varchar(255),
    summary        varchar(255),
    active         boolean        not null,
    wallet_balance numeric(12, 2) not null,
    version        bigint
);

create table learners (
    id               bigint generated by default as identity primary key,
    student_number   varchar(255)   not null unique,
    first_name       varchar(255)   not null,
    last_name        varchar(255)   not null,
    grade            varchar(255)   not null,
    campus           varchar(255)   not null,
    house            varchar(255),
    card_token       varchar(255)   not null unique,
    wallet_balance   numeric(12, 2) not null,
    daily_limit      numeric(12, 2) not null,
    spent_today      numeric(12, 2) not null,
    spent_on         date,
    frozen           boolean        not null,
    version          bigint,
    tuck_mode        varchar(255)   not null,
    goal_name        varchar(255),
    goal_target      numeric(12, 2),
    goal_saved       numeric(12, 2)
);
create index ix_learners_campus_grade on learners (campus, grade);

create table learner_sports (
    learner_id bigint not null references learners (id),
    sport      varchar(255)
);
create table learner_sizes (
    learner_id bigint       not null references learners (id),
    size_type  varchar(255) not null,
    size_value varchar(255),
    primary key (learner_id, size_type)
);
create table learner_guardians (
    learner_id bigint not null references learners (id),
    account_id bigint not null references accounts (id),
    primary key (learner_id, account_id)
);
create table learner_blocked_categories (
    learner_id bigint not null references learners (id),
    category   varchar(255)
);
create table learner_allowed_items (
    learner_id bigint not null references learners (id),
    item_name  varchar(255)
);

create table role_assignments (
    id            bigint generated by default as identity primary key,
    account_id    bigint       not null references accounts (id),
    role          varchar(255) not null,
    label         varchar(255),
    campus        varchar(255),
    grade         varchar(255),
    class_name    varchar(255),
    learner_id    bigint references learners (id),
    verified      boolean      not null,
    verified_note varchar(255),
    position      integer      not null
);

create table access_requests (
    id             bigint generated by default as identity primary key,
    account_id     bigint       not null references accounts (id),
    requested_role varchar(255) not null,
    ask            varchar(255),
    how            varchar(255),
    status         varchar(255),
    created_at     timestamp(6),
    decided_at     timestamp(6)
);
create table access_request_learners (
    request_id bigint not null references access_requests (id),
    learner_id bigint
);

-- ============================== wallets ==============================
create table wallet_transactions (
    id          bigint generated by default as identity primary key,
    account_id  bigint references accounts (id),
    learner_id  bigint references learners (id),
    type        varchar(255)   not null,
    description varchar(255)   not null,
    amount      numeric(12, 2) not null,
    created_at  timestamp(6)   not null
);
create index ix_wallet_tx_account on wallet_transactions (account_id);
create index ix_wallet_tx_learner on wallet_transactions (learner_id);

-- ============================== tuckshop ==============================
create table menu_items (
    id        bigint generated by default as identity primary key,
    name      varchar(255)   not null unique,
    price     numeric(10, 2) not null,
    category  varchar(255)   not null,
    available boolean        not null
);

create table pre_orders (
    id                bigint generated by default as identity primary key,
    learner_id        bigint         not null references learners (id),
    service_day       date           not null,
    total             numeric(10, 2) not null,
    pay_from          varchar(255)   not null,
    payer_account_id  bigint references accounts (id),
    status            varchar(255)   not null,
    repeat_weekly     boolean        not null,
    last_collected_at time(6),
    created_at        timestamp(6),
    constraint uk_pre_orders_learner_day unique (learner_id, service_day)
);
create index ix_pre_orders_day on pre_orders (service_day);

create table pre_order_lines (
    pre_order_id bigint         not null references pre_orders (id),
    line_no      integer        not null,
    item_name    varchar(255)   not null,
    category     varchar(255),
    unit_price   numeric(10, 2) not null,
    quantity     integer        not null,
    collected    boolean        not null,
    collected_at time(6),
    primary key (pre_order_id, line_no)
);

-- ============================== savings ==============================
create table savings_pots (
    id            bigint generated by default as identity primary key,
    account_id    bigint         not null unique references accounts (id),
    balance       numeric(12, 2) not null,
    goal          numeric(12, 2) not null,
    monthly_debit numeric(12, 2) not null,
    opens_on      date           not null,
    version       bigint,
    share_token   varchar(255)   not null unique
);

create table savings_contributions (
    id             bigint generated by default as identity primary key,
    pot_id         bigint         not null references savings_pots (id),
    from_name      varchar(255)   not null,
    amount         numeric(12, 2) not null,
    contributed_on date           not null
);

create table pocket_money_rules (
    id          bigint generated by default as identity primary key,
    account_id  bigint         not null references accounts (id),
    learner_id  bigint         not null references learners (id),
    amount      numeric(10, 2) not null,
    day_of_week varchar(255)   not null,
    enabled     boolean        not null
);

-- ============================== school ==============================
create table school_ledger (
    id          bigint generated by default as identity primary key,
    occurred_at timestamp(6)   not null,
    description varchar(255)   not null,
    amount      numeric(12, 2) not null,
    payer_name  varchar(255),
    source      varchar(255)   not null
);
create index ix_school_ledger_occurred on school_ledger (occurred_at);

create table school_settings (
    id               bigint  not null primary key,
    approve_notices  boolean not null,
    approve_homework boolean not null
);

-- ============================== shop ==============================
create table uniform_items (
    id        bigint generated by default as identity primary key,
    campus    varchar(255)   not null,
    name      varchar(255)   not null,
    price     numeric(10, 2) not null,
    kind      varchar(255)   not null,
    size_type varchar(255),
    supplier  varchar(255)
);

create table sport_offers (
    id    bigint generated by default as identity primary key,
    sport varchar(255)   not null,
    type  varchar(255)   not null,
    name  varchar(255)   not null,
    price numeric(10, 2) not null
);

create table supply_lists (
    id     bigint generated by default as identity primary key,
    campus varchar(255) not null,
    grade  varchar(255) not null,
    status varchar(255) not null,
    constraint uk_supply_lists_campus_grade unique (campus, grade)
);

create table supply_list_items (
    id         bigint generated by default as identity primary key,
    list_id    bigint         not null references supply_lists (id),
    name       varchar(255)   not null,
    quantity   integer        not null,
    unit_price numeric(10, 2) not null,
    position   integer        not null
);

create table preloved_listings (
    id                bigint generated by default as identity primary key,
    campus            varchar(255)   not null,
    name              varchar(255)   not null,
    price             numeric(10, 2) not null,
    price_new         numeric(10, 2),
    size_type         varchar(255),
    size              varchar(255),
    sport             varchar(255),
    seller_account_id bigint references accounts (id),
    seller_label      varchar(255),
    sold              boolean        not null,
    version           bigint,
    listed_at         timestamp(6)
);

create table cart_items (
    id          bigint generated by default as identity primary key,
    account_id  bigint         not null references accounts (id),
    learner_id  bigint         not null references learners (id),
    category    varchar(255)   not null,
    product_key varchar(255)   not null,
    name        varchar(255)   not null,
    unit_price  numeric(10, 2) not null,
    quantity    integer        not null,
    size        varchar(255),
    note        varchar(255),
    preloved_id bigint
);

create table shop_orders (
    id             bigint generated by default as identity primary key,
    order_number   varchar(255) unique,
    account_id     bigint         not null references accounts (id),
    placed_at      timestamp(6)   not null,
    subtotal       numeric(12, 2) not null,
    delivery_fee   numeric(12, 2) not null,
    total          numeric(12, 2) not null,
    delivery       varchar(255),
    payment_method varchar(255)
);

create table shop_order_lines (
    id         bigint generated by default as identity primary key,
    order_id   bigint         not null references shop_orders (id),
    learner_id bigint         not null references learners (id),
    category   varchar(255)   not null,
    name       varchar(255)   not null,
    unit_price numeric(10, 2) not null,
    quantity   integer        not null,
    size       varchar(255),
    note       varchar(255)
);

create table uniform_stock (
    id                bigint generated by default as identity primary key,
    item_name         varchar(255) not null,
    stock_size        varchar(255) not null,
    quantity          integer      not null,
    restock_requested boolean      not null,
